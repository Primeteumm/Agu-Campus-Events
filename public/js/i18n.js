function i18nGet(key) {
    const lang = i18nGetLang();
    const parts = key.split('.');
    let val = I18N[lang];
    for (const p of parts) {
        if (val == null) return key;
        val = val[p];
    }
    return val != null ? val : key;
}

function i18nGetLang() {
    return localStorage.getItem('lang') || 'en';
}

function i18nSetLang(lang) {
    localStorage.setItem('lang', lang);
    document.documentElement.lang = lang;
    i18nApply();
    i18nUpdateToggle();
    window.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
}

function i18nApply() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.innerHTML = i18nGet(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.placeholder = i18nGet(key);
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        el.title = i18nGet(key);
    });
}

function i18nUpdateToggle() {
    const lang = i18nGetLang();
    const enBtn = document.getElementById('langEN');
    const trBtn = document.getElementById('langTR');
    if (enBtn) enBtn.classList.toggle('lang-btn--active', lang === 'en');
    if (trBtn) trBtn.classList.toggle('lang-btn--active', lang === 'tr');
}

function i18nInit() {
    const lang = i18nGetLang();
    document.documentElement.lang = lang;
    i18nApply();
    i18nUpdateToggle();

    document.getElementById('langEN')?.addEventListener('click', () => i18nSetLang('en'));
    document.getElementById('langTR')?.addEventListener('click', () => i18nSetLang('tr'));
}

document.addEventListener('DOMContentLoaded', i18nInit);
